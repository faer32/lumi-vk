  /* Приводит код языка платформы к одному из поддерживаемых. */
  G.pickLang = function (code) {
    code = String(code || '').toLowerCase().slice(0, 2);
    if (code === 'tr') return 'tr';
    if (['ru', 'be', 'kk', 'uk', 'uz'].indexOf(code) >= 0) return 'ru';
    return 'en';
  };

  G.setLang = function (l) { G.lang = L[l] ? l : 'en'; };

  G.t = function (key, a, b) {
    var s = L[G.lang][key];
    if (s === undefined) s = L.en[key];
    if (s === undefined) return key;
    if (a !== undefined) s = s.replace('{0}', a);
    if (b !== undefined) s = s.replace('{1}', b);
    return s;
  };
